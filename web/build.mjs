// Bundles the official filament.js/filament.wasm 1.78.0 web release with the Aqua_Filament adapter into one
// self-contained ES module (runtimes/web/aqua_filament.mjs) for the AquariusLang DynamicLibrary web loader.
// Usage: node web/build.mjs [path/to/filament-v1.78.0-web]
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const filamentDir = process.argv[2] || process.env.FILAMENT_WEB || join(root, 'native', 'third_party', 'filament-web');
const js = readFileSync(join(filamentDir, 'filament.js'), 'utf8');
const wasm = readFileSync(join(filamentDir, 'filament.wasm'));
const adapter = readFileSync(join(here, 'src', 'adapter.mjs'), 'utf8');
// filament.js is classic (sloppy-mode) script code: evaluate it in its own function scope and expose an
// initializer that rebinds the scope's `Filament` variable to the instantiated module, like Filament.init().
const prologue = `// Aqua_Filament web runtime. Contains Filament 1.78.0 (Apache-2.0, Copyright Google LLC) - see licenses/.
// Generated by web/build.mjs - do not edit.
let Filament = new Function(${JSON.stringify(js + `
;Filament.__aquaInit = async function (wasmBinary) {
  const module = await Filament({wasmBinary});
  Filament = Object.assign(module, Filament);
  Filament.assets = {};
  Filament.loadClassExtensions();
  return Filament;
};
return Filament;`)})();
const FILAMENT_WASM_BASE64 = ${JSON.stringify(wasm.toString('base64'))};
`;
mkdirSync(join(root, 'runtimes', 'web'), {recursive: true});
const out = join(root, 'runtimes', 'web', 'aqua_filament.mjs');
writeFileSync(out, prologue + adapter);
console.log(`Built ${out} (${(Buffer.byteLength(prologue + adapter) / 1048576).toFixed(1)} MiB)`);
